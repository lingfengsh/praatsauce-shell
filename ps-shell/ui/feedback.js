// 反馈收集表链接 + 软件版本（两处配置，都在这一文件）
// ---------------------------------------------------------------------
// 1) 反馈按钮：用户点「反馈」会用浏览器打开 PRAATSAUCE_FEEDBACK_URL 去填。
//    推荐用【问卷星】建「公开表单」（免费账号即可，填写人无需登录），
//    把填写链接粘到引号里即可（就这一处，向导版与 VoiceSauce 版共用）。
//
// 2) 软件版本：显示在「关于本软件」弹窗里。发布新版本时只改这一行。
//
// 推荐收集表字段（照抄即可）：
//   ① 反馈类型  单选必填：功能建议 / Bug报错 / 使用问题 / 其他
//   ② 软件版本  单行选填：提示「顶栏『关于本软件』里查」
//   ③ 反馈内容  多行必填
//   ④ 联系方式  单行选填：标注「选填，不填也能提交」
// 用户填完 → 你在问卷星后台点「导出」拿到 Excel/CSV → 把文件丢给我，
//   我一次性分类汇总（按类型/去重/排优先级），你不用一条条复制。
// =====================================================================
window.PRAATSAUCE_FEEDBACK_URL = 'https://www.wjx.top/vm/rTo7Eb7.aspx';  // ← 粘贴你的问卷星公开表单【填写链接】到这里
window.PRAATSAUCE_VERSION = '向导界面 1.2';  // ← 发布新版本时改这一行（大版本不动，小版本 +1）

window.openFeedback = function () {
  const url = (window.PRAATSAUCE_FEEDBACK_URL || '').trim();
  if (!url) {
    alert('反馈收集表链接尚未配置（ui/feedback.js 中的 PRAATSAUCE_FEEDBACK_URL 还是空的）。');
    return;
  }
  window.open(url, '_blank', 'noopener,noreferrer');
};
